"""Design the bass engine's half-band decimators and write firmware/engine/be_hb.h.
  HB : 88.2 -> 44.1 kHz (after the ladder): passband to 20 kHz, stopband from 24.1 kHz, so nothing folds below 20 kHz.
  HB4: 176.4 -> 88.2 kHz (after the oscillators): passband to 20 kHz, stopband from 68.2 kHz (what would fold
       below 20 kHz at 88.2 kHz). Both ~100 dB.
Run: .venv/bin/python tools/gen_halfband.py"""
import numpy as np
from scipy.signal import remez, freqz
from pathlib import Path


def design(fs, passband, target_db=-96.0):
    stop = fs / 2 - passband                         # half-band: symmetric around fs/4
    for ntaps in range(7, 400, 4):                   # 4k+3 taps: odd, centre 0.5, every other tap zero
        h = remez(ntaps, [0, passband, stop, fs / 2], [1, 0], fs=fs)
        c = ntaps // 2
        for i in range(ntaps):
            if (i - c) % 2 == 0 and i != c:
                h[i] = 0.0
        h[c] = 0.5
        h /= h.sum()
        w, H = freqz(h, worN=1 << 15, fs=fs)
        sb = 20 * np.log10(np.max(np.abs(H[w >= stop])) + 1e-20)
        if sb < target_db:
            break
    pb = np.abs(H[w <= passband])
    ripple = 20 * np.log10(pb.max()) - 20 * np.log10(pb.min())
    odd = [h[i] for i in range(ntaps) if (i - c) % 2 == 1 and i < c]
    return ntaps, odd, sb, ripple, stop


def emit(prefix, fs, passband):
    n, odd, sb, rip, stop = design(fs, passband)
    print(f"{prefix}: {fs/1000:.1f} kHz, {n} taps, {len(odd)} non-zero per side, stopband {sb:.1f} dB from {stop:.0f} Hz, ripple {rip:.4f} dB")
    vals = ",\n    ".join(", ".join(f"{v:.9e}f" for v in odd[i:i + 4]) for i in range(0, len(odd), 4))
    return (f"/* {fs/1000:.1f} -> {fs/2000:.2f} kHz: {n} taps, passband 0..{passband:.0f} Hz (ripple {rip:.4f} dB), "
            f"stopband from {stop:.0f} Hz at {sb:.1f} dB */\n"
            f"#define {prefix}_TAPS {n}\n#define {prefix}_NODD {len(odd)}\n"
            f"BE_HB_TABLE float {prefix}_ODD[{prefix}_NODD] = {{   /* outermost first; mirrored on the right */\n    {vals}}};\n")


out = Path(__file__).resolve().parent.parent / "firmware" / "engine" / "be_hb.h"
out.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_halfband.py: the engine's half-band "
               "decimators (centre tap 0.5, every other tap zero). Do not edit. */\n#ifndef BE_HB_H\n#define BE_HB_H\n"
               "#ifdef BE_RAM_CODE\n#define BE_HB_TABLE static          /* in RAM (.data): the RAM code reads it */\n#else\n#define BE_HB_TABLE static const\n#endif\n"
               + emit("BE_HB", 88200.0, 20000.0) + emit("BE_HB4", 176400.0, 20000.0) + "#endif\n")
print("wrote", out)
