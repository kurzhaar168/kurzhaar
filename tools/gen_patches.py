"""Turn patches/*.txt into firmware/engine/be_patches.h: one function per patch that sets the defaults, then the
patch's values. Run: .venv/bin/python tools/gen_patches.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
fields = re.findall(r"^\s*float ([a-z0-9_, ]+);", (ROOT / "firmware" / "engine" / "be.h").read_text(), re.M)
known = {f.strip() for line in fields for f in line.split(",")}
out, names = [], []
for i, path in enumerate(sorted((ROOT / "patches").glob("*.txt"))):
    sets = []
    for line in path.read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        name, value = (s.strip() for s in line.split("="))
        if name not in known:
            raise SystemExit(f"{path.name}: unknown parameter {name}")
        sets.append(f"    p->{name} = {float(value)!r}f;")
    label = path.stem.split("_", 1)[1].replace("_", " ").upper() if "_" in path.stem else path.stem.upper()
    names.append(f'"{label[:16]}"')
    out.append(f"static void be_patch_{i}(be_patch_t *p)   /* {path.name} */\n{{\n    be_patch_default(p);\n"
               + "\n".join(sets) + "\n}\n")
hdr = ROOT / "firmware" / "engine" / "be_patches.h"
hdr.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Copyright (C) 2026 JazzMasterT */\n/* Generated by tools/gen_patches.py from the patch files in patches/. "
               "Do not edit. */\n#ifndef BE_PATCHES_H\n#define BE_PATCHES_H\n#include \"be.h\"\n\n" + "\n".join(out)
               + f"\n#define BE_NPATCH {len(names)}u\nstatic void (*const BE_PATCH_FN[BE_NPATCH])(be_patch_t *) = {{"
               + ", ".join(f"be_patch_{i}" for i in range(len(names))) + "};\n"
               + f"static const char *const BE_PATCH_NAME[BE_NPATCH] = {{{', '.join(names)}}};\n#endif\n")
print(f"wrote {hdr} ({len(names)} patches)")
